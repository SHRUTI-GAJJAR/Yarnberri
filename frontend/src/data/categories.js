/**
 * Single source of truth for the collection taxonomy and its artwork.
 *
 * Both the home page cards (components/home/CategorySection.jsx) and the shop
 * page filter pills (pages/shop/ShopPage.jsx) read from here, so a collection
 * can never be artwork'd on one page and bare on the other.
 *
 * `slug` is what appears in the URL (`/shop?category=<slug>`) and is what the
 * backend stores on a product, so these strings have to match the `category`
 * field in the database.
 *
 * `image` is the full-size 1254 px artwork used by the home page cards.
 * `thumb` is the small version used as an icon inside the shop filter pills -
 * generated by `frontend/scripts/make-category-thumbs.py`, which crops to the
 * artwork, keys out any flat background, and scales down to 96 px. The full-size
 * sources are 1.5-3 MB each and far too heavy to load six of them for a row of
 * 24 px icons.
 *
 * `icon` is a lucide fallback, used only if `image` is ever removed.
 *
 * To add a collection: drop the artwork into public/images/categories/, add an
 * entry here, add the matching source-to-slug line in
 * `scripts/make-category-thumbs.py`, and re-run that script. Never point two
 * collections at the same file.
 */
